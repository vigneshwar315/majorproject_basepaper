"""Page C - Candidate plans produced by the backend."""

from __future__ import annotations

import html

import streamlit as st

from frontend import charts, helpers, theme
from paper_replication.reference_metrics import DESCRIPTIONS, EXTENSION_METRICS, PAPER_METRICS


def _metric_origin(mid: str, dyn: dict) -> str:
    if mid in dyn:
        return "generated by DMG (validated)"
    if mid in PAPER_METRICS:
        return "paper Table 2 (reference implementation)"
    if mid in EXTENSION_METRICS:
        return "extension, not in the paper"
    return ""


def render() -> None:
    theme.page_header("Candidate plans", "The alternative plans the heuristic produced, their computed metrics, the deterministic feasibility verdicts and the plan the decision step chose.")
    res = st.session_state.get("result")
    if res is None:
        st.info("No plans yet. On **Problem configuration**, press **Run full demo**, or load an instance, write a preference and press **Run optimization**.")
        return
    inst = res.instance
    sel = st.session_state.get("selected_plan")
    if res.provider_info.get("is_mock"):
        st.markdown(theme.badge("mock", "This run used the mock provider") + theme.badge("synthetic") if inst.synthetic else theme.badge("mock", "This run used the mock provider"), unsafe_allow_html=True)
    cmp_df = helpers.comparison_table(res.plans, res.matrix, res.metric_ids, sel)

    n_feas = int(cmp_df["feasible"].sum())
    k1, k2, k3, k4 = st.columns(4)
    k1.metric("Candidate plans", len(res.plans))
    k2.metric("Feasible (validator)", n_feas)
    k3.metric("Requests received", len(inst.received_requests()))
    k4.metric("Selected plan", sel or "none")

    if res.candidate_set.notes:
        for n in res.candidate_set.notes:
            st.warning(n)

    st.subheader("Selected plan")
    if res.mcdm and res.mcdm.success and sel in res.matrix:
        left, right = st.columns(2, gap="medium")
        with left:
            vals = res.matrix[sel]
            plan = next(p for p in res.plans if p.plan_id == sel)
            show = [m for m in res.metric_ids if m in ("z1", "z2", "z3", "z4", "z9", "z10") or m in res.dynamic_metric_texts]
            facts = f"Plan <b>{html.escape(sel)}</b> passed the deterministic constraint validator ({'feasible' if plan.feasible else 'NOT feasible'}). " + \
                    f"{len(plan.accepted_ids())} accepted, {len(plan.rejected_ids())} rejected requests.<br>" + \
                    "<br>".join(f"{m} = {vals[m]:.4g}" for m in show)
            theme.fact_box(facts)
        with right:
            theme.llm_box(res.mcdm.justification, res.mcdm.is_mock)
    elif res.mcdm:
        st.error(f"The decision step did not return a valid plan: {res.mcdm.error}")
    else:
        st.info("The decision step was not run (no feasible plan).")

    st.subheader("Comparison table")
    show_cols = ["plan", "feasible", "accepted", "rejected", "routes", "policy"] + res.metric_ids + ["selected"]
    styled = cmp_df[show_cols].style.apply(lambda row: ["background-color:#FBE7EA" if row["selected"] == "yes" else "" for _ in row], axis=1).format({m: "{:.4g}" for m in res.metric_ids})
    st.dataframe(styled, hide_index=True, width="stretch")
    st.caption("Metric values are computed by code from the plans. z1 to z10 follow Table 2 of the paper; z11 to z14 are extensions; d1, d2, ... are metrics produced by DMG.")
    st.download_button("Download comparison table (CSV)", cmp_df.to_csv(index=False), f"{res.run_id}_comparison.csv", "text/csv")

    st.subheader("Charts")
    feas = cmp_df[cmp_df["feasible"]]
    if feas.empty:
        st.info("No feasible plan to chart.")
    else:
        c1, c2, c3 = st.columns(3)
        xm = c1.selectbox("Horizontal axis", res.metric_ids, index=res.metric_ids.index("z3") if "z3" in res.metric_ids else 0, key="sx")
        ym = c2.selectbox("Vertical axis", res.metric_ids, index=0, key="sy")
        bm = c3.selectbox("Metric for the bar chart", res.metric_ids, index=0, key="sb")
        a, b = st.columns(2)
        a.plotly_chart(charts.metric_scatter(cmp_df, xm, ym, sel), width="stretch")
        b.plotly_chart(charts.metric_bar(cmp_df, bm, sel), width="stretch")
        with st.expander("Parallel view of the metrics"):
            pm = st.multiselect("Metrics", res.metric_ids, default=[m for m in res.metric_ids if m in PAPER_METRICS][:6], key="pm")
            if len(pm) >= 2:
                st.plotly_chart(charts.parallel_figure(cmp_df, pm, sel), width="stretch")
            else:
                st.caption("Choose at least two metrics.")

    st.subheader("Inspect one plan")
    ids = [p.plan_id for p in res.plans]
    default = ids.index(sel) if sel in ids else 0
    pid = st.selectbox("Plan", ids, index=default, key="inspect_plan")
    plan = next(p for p in res.plans if p.plan_id == pid)
    st.markdown(theme.badge("verified", "Feasible" if plan.feasible else "Violates constraints"), unsafe_allow_html=True)
    t1, t2, t3, t4 = st.tabs(["Routes", "Request decisions", "Constraint check", "Metrics of this plan"])
    with t1:
        if not plan.routes:
            st.info("This plan has no routes (every request was rejected).")
        else:
            st.dataframe(helpers.route_summary_table(inst, plan), hide_index=True, width="stretch")
            days = sorted({r.day for r in plan.routes})
            day = st.selectbox("Day to draw", days, key="route_day")
            st.plotly_chart(charts.route_figure(inst, plan, int(day)), width="stretch")
            st.caption("Drawn on the instance's abstract planar coordinates. This is a route graph, not a geographic map.")
            with st.expander("Stop-by-stop timings"):
                st.dataframe(helpers.route_table(inst, plan), hide_index=True, width="stretch")
    with t2:
        st.dataframe(helpers.decisions_table(plan), hide_index=True, width="stretch")
        st.caption("Rejection reasons: 'no feasible insertion' (hard constraints) or a policy rule of this candidate (e.g. tight time window, detour limit).")
    with t3:
        if plan.violations:
            for v in plan.violations:
                st.error(v)
        else:
            st.success("No hard-constraint violation: capacity, pickup before delivery, time windows, shift length, depot closing time and request coverage all pass.")
        st.caption("Policy parameters that shaped this candidate (they are not hard constraints):")
        st.json(plan.policy.to_dict(), expanded=False)
    with t4:
        vals = res.matrix.get(pid)
        if vals is None:
            st.info("This plan is infeasible and has no metric row.")
        else:
            rows = [{"metric": m, "value": vals[m], "meaning": res.dynamic_metric_texts.get(m) or DESCRIPTIONS.get(m, ""), "origin": _metric_origin(m, res.dynamic_metric_texts)} for m in res.metric_ids]
            import pandas as pd

            st.dataframe(pd.DataFrame(rows), hide_index=True, width="stretch")
